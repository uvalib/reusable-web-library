#!/usr/bin/env node
// Syncs scalar SCSS variables from the Drupal theme into src/styles/tokens.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_THEME = '../monorepo/packages/drupal_library_theme/src/scss/base';
const FILES = ['_colors.scss', '_spacing.scss'];
const LINE = /^\$([a-zA-Z0-9_-]+):\s*([^;()]+);/;

/**
 * Parse top-level scalar `$name: value;` lines. Skips comments, maps, `@` rules,
 * and values that reference another `$variable` (CSS can't evaluate SCSS math).
 * A repeated name keeps its first position with the last value (SCSS semantics).
 * @param {string} text
 * @returns {Array<[string, string]>}
 */
export function parseScssVars(text) {
  const vars = new Map();
  for (const line of text.split('\n')) {
    const m = LINE.exec(line);
    if (!m) continue;
    const value = m[2].trim();
    if (!value || value.includes('$')) continue;
    vars.set(m[1], value);
  }
  return [...vars];
}

function main() {
  const args = process.argv.slice(2);
  const i = args.indexOf('--theme');
  const themeArg = i >= 0 ? args[i + 1] : DEFAULT_THEME;
  if (!themeArg) throw new Error('--theme requires a directory');
  const themeDir = resolve(root, themeArg);

  const vars = new Map();
  for (const file of FILES) {
    for (const [name, value] of parseScssVars(readFileSync(join(themeDir, file), 'utf8'))) {
      vars.set(name, value);
    }
  }
  const decls = [
    ...[...vars].map(([n, v]) => `  --${n}: ${v};`),
    '  --uva-font-family: franklin-gothic-urw, Arial, Helvetica, sans-serif;',
    '  --uva-font-size-base: 17px;',
  ];
  const out = `// GENERATED by scripts/sync-tokens.mjs from ${relative(root, themeDir) || '.'} — do not edit
import { css } from 'lit';

export const tokens = css\`
  :root {
${decls.map((d) => '  ' + d).join('\n')}
  }
\`;
`;
  writeFileSync(join(root, 'src/styles/tokens.ts'), out);
  console.log(`wrote src/styles/tokens.ts (${decls.length} properties)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
